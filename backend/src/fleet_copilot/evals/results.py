"""The markdown summary of a run (`--write-results PATH`): suites, the metrics block, failing instances.

Everything in it is already in the run report; nothing here holds an answer's text. A failing instance shows
the names of its failing checks and the first failure's detail, cut to a table-friendly length.
"""

from __future__ import annotations

from pathlib import Path

from fleet_copilot.evals import metrics
from fleet_copilot.evals.runner import RunResult

DETAIL_LIMIT = 120


def _cell(text: str, limit: int | None = None) -> str:
    """One table cell: a single line, pipes escaped, optionally cut to `limit` characters."""
    flat = " ".join(text.split())
    if limit is not None and len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    return flat.replace("|", "\\|")


def _suite_rows(result: RunResult) -> list[str]:
    totals = result.totals
    rows = [
        "| suite | passed/total | rate | not recorded |",
        "| --- | --- | --- | --- |",
    ]
    for name, tally in [*totals["suites"].items(), ("overall", totals["overall"])]:
        rate = f"{tally['rate'] * 100:.1f}%"
        label = f"**{name}**" if name == "overall" else name
        rows.append(
            f"| {label} | {tally['passed']}/{tally['total']} | {rate} | {tally['not_recorded']} |"
        )
    return rows


def _failing_rows(result: RunResult) -> list[str]:
    rows = [
        "| instance | failing checks | first failure |",
        "| --- | --- | --- |",
    ]
    for case in result.cases:
        if case.passed:
            continue
        failed = [c for c in case.checks if not c["passed"]]
        names = ", ".join(dict.fromkeys(c["name"] for c in failed)) or "none"
        first = failed[0]["detail"] if failed else ""
        rows.append(f"| `{case.instance_id}` | {_cell(names)} | {_cell(first, DETAIL_LIMIT)} |")
    return rows


def format_results(result: RunResult) -> str:
    """The whole results document as markdown (ends with a newline)."""
    totals = result.totals
    failing = _failing_rows(result)
    mode = "replay" if result.replay else "live"
    lines = [
        "# Evaluation results",
        "",
        "Generated by `make eval-results` from the committed cassette; do not edit by hand.",
        "",
        f"- run: `{result.run_id}` ({result.model_mode})",
        f"- dataset: `{result.dataset_sha256[:12]}`, as of {result.as_of}",
        "",
        "## Suites",
        "",
        *_suite_rows(result),
        "",
        "## Metrics",
        "",
        metrics.format_metrics(totals, replay=result.replay),
        "",
        (
            "Latency is replay latency (the model is answered from the cassette), so it measures "
            "the agent's own code, not the model."
            if mode == "replay"
            else "Latency is the wall time of each turn including the live model."
        ),
        "",
        "## Failing instances",
        "",
        *(failing if len(failing) > 2 else ["None."]),
        "",
    ]
    return "\n".join(lines)


def write_results(result: RunResult, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_results(result), encoding="utf-8")
    return path
